'use strict';
/* P08 R16: synthetic browser → real Kuma → genuine immutable P08 HTML. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.P08_PLAYWRIGHT_ROOT + '/node_modules/playwright');
const path = require('node:path');
const { URL } = require('node:url');

(async () => {
  const temp = process.env.P08_R16_TMP;
  assert(temp && temp.includes('/p08-kuma/'));
  const token = fs.readFileSync(path.join(temp, 'key'), 'utf8').trim();
  const tracking = fs.readFileSync(path.join(temp, 'tracking-url'), 'utf8').trim();
  assert(token.startsWith('kuma_'));
  assert(tracking.startsWith('https://kuma.example.test/'));
  const browser = await chromium.launch({
    headless: true,
    args: ['--no-proxy-server', '--host-resolver-rules=MAP kuma.example.test 127.0.0.1,MAP lander.example.test 127.0.0.1']
  });
  try {
    const ctx = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 390, height: 844 } });
    const page = await ctx.newPage();
    const invalids = [
      'https://lander.example.test/landing/r15',
      'https://lander.example.test/landing/r15?click_id=invalid',
    ];
    for (const url of invalids) {
      const resp = await page.goto(url, { waitUntil: 'load' });
      assert.equal(resp.status(), 200);
      const button = page.locator('a[data-kuma-exit]');
      assert.equal(await button.count(), 1);
      assert.equal(await button.getAttribute('href'), null, 'invalid/missing click ID must have no href');
      assert.equal(await button.getAttribute('aria-disabled'), 'true');
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      assert(overflow <= 1, '390px horizontal overflow: ' + overflow);
    }
    console.log('P08_R16_CHROMIUM_MISSING_AND_INVALID_CLICK_FAIL_CLOSED_PASS');

    // Use the actual URL generated by the genuine upstream Kuma campaign.
    const url = tracking.replace(/\{[A-Za-z_0-9]+\}/g, 'synthetic');
    const response = await page.goto(url, { waitUntil: 'load', timeout: 30000 });
    assert.equal(response.status(), 200, 'tracking URL should land on published P08 HTML');
    assert.equal(new URL(page.url()).hostname, 'lander.example.test');
    const clickId = new URL(page.url()).searchParams.get('click_id');
    assert.match(clickId || '', /^[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}$/i);
    assert.equal(await page.locator('h1').textContent(), 'Verified synthetic landing page');
    const button = page.locator('a[data-kuma-exit]');
    await page.waitForFunction(() => {
      const el = document.querySelector('a[data-kuma-exit]');
      return el && el.hasAttribute('href') && !el.hasAttribute('aria-disabled');
    });
    const dest = new URL(await button.getAttribute('href'));
    assert.equal(dest.hostname, 'kuma.example.test');
    assert.equal(dest.pathname, '/click.php');
    assert.equal(dest.searchParams.get('click_id'), clickId);
    const html = await page.content();
    assert(!html.includes(token), 'P08 published HTML leaked a Kuma API credential');
    assert(!html.includes('href="https://offers.example.test/direct"'));
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    assert(overflow <= 1, 'tracked 390px horizontal overflow: ' + overflow);
    console.log('P08_R16_REAL_KUMA_CLICK_TO_ACTUAL_P08_STATIC_HTML_AND_CSP_JS_PASS');

    // The exit is followed through the genuine Kuma click.php endpoint.
    // Only the final synthetic external offer URL is fulfilled locally.
    let offersSeen = 0;
    await page.route('https://offers.example.test/**', async route => {
      offersSeen++;
      await route.fulfill({
        status: 200,
        contentType: 'text/html',
        body: '<!doctype html><title>R16 synthetic offer</title><p>Only a browser fixture.</p>',
      });
    });
    await Promise.all([
      page.waitForURL(u => u.hostname === 'offers.example.test', { timeout: 30000 }),
      button.click(),
    ]);
    assert.equal(offersSeen, 1);
    assert.equal(new URL(page.url()).hostname, 'offers.example.test');
    assert.equal(new URL(page.url()).pathname, '/out');
    console.log('P08_R16_CHROMIUM_P08_CTA_TO_REAL_KUMA_CLICK_PHP_AND_SYNTHETIC_OFFER_PASS');

    // Synthetic S2S Postback must be recorded by Kuma, not by P08.
    const postback = new URL('https://kuma.example.test/postback.php');
    for (const [k,v] of Object.entries({
      click_id:clickId, txid:'p08-r16-browser-0001', payout:'1.75', status:'approved'
    })) postback.searchParams.set(k,v);
    const result = await ctx.request.get(postback.href, { timeout: 20000 });
    assert.equal(result.status(), 200);
    const resp = await ctx.request.get('https://kuma.example.test/api/v1/conversions?campaign_id=1', {
      headers:{ Authorization:'Bearer '+token }, timeout:20000,
    });
    assert.equal(resp.status(),200);
    const json = await resp.json();
    assert(Array.isArray(json.data) && json.data.some(c => c.click_id === clickId),
           'Kuma must independently read back the exact browser Click ID conversion');
    console.log('P08_R16_BROWSER_CLICK_ID_POSTBACK_KUMA_CONVERSION_READBACK_PASS');

    await page.setViewportSize({width:1440,height:900});
    const staticPage=await page.goto('https://lander.example.test/landing/r15?click_id='+clickId);
    assert.equal(staticPage.status(),200);
    const desktopOverflow=await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    assert(desktopOverflow <= 1,'1440px horizontal overflow: '+desktopOverflow);
    console.log('P08_R16_CHROMIUM_390_1440_NO_HORIZONTAL_OVERFLOW_PASS');
    await ctx.close();
  } finally {
    await browser.close();
  }
})().catch(err => {
  // Errors contain only synthetic fixture URLs and assertion identifiers.
  console.error('P08_R16_CHROMIUM_CHAIN_FAIL=' + err.message.split('\n')[0].slice(0,260));
  process.exitCode=1;
});
